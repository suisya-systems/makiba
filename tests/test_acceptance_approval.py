TEST_BODY = "from lib import answer\n\n\ndef test_answer():\n    assert answer() == 2\n"
CARGO_TOML = '[package]\nname = "makiba"\nversion = "0.0.0"\nedition = "2021"\n'
CARGO_LOCK = (
    "# This file is automatically @generated by Cargo.\n"
    "# It is not intended for manual editing.\n"
    "version = 4\n\n"
    '[[package]]\nname = "makiba"\nversion = "0.0.0"\n'
)
LIB_RS = "pub fn answer() -> u32 {\n    %d\n}\n"
RS_BODY = "#[test]\nfn answer_is_two() {\n    assert_eq!(makiba::answer(), 2);\n}\n"
APPROVED = "acceptance-check: approved by the owner"


def run(args, cwd=None, env=None):
    return subprocess.run(args, cwd=cwd, env=env or ENV, check=True, capture_output=True, text=True).stdout


def make_key(folder: Path, name: str) -> Path:
    key = folder / name
    run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", name, "-f", str(key)])
    return key


def signers_line(key: Path) -> str:
    pub = (key.parent / (key.name + ".pub")).read_text(encoding="utf-8").strip()
    return f'makiba-owner namespaces="{NAMESPACE}" {pub}\n'


class Repo:
    """A scratch repository: base on main, then a checked-out branch feat/x. The base holds
    lib.py (answers 1), a Cargo package named makiba, a workflow, tests/conftest.py,
    tests/data.json, a stand-in scripts/acceptance-check.sh and, when given, the signers file
    .github/acceptance-approvers."""

    def __init__(self, path: Path, signers: str | None):
        self.path = path
        path.mkdir()
        self.g("init", "-q", "-b", "main")
        self.write("lib.py", "def answer():\n    return 1\n")
        self.write("Cargo.toml", CARGO_TOML)
        self.write("Cargo.lock", CARGO_LOCK)
        self.write("src/lib.rs", LIB_RS % 1)
        self.write(".github/workflows/ci.yml", "name: CI\n")
        self.write("tests/conftest.py", "# helper\n")
        self.write("tests/data.json", "{}\n")
        self.write("scripts/acceptance-check.sh", "#!/usr/bin/env bash\necho stand-in\n")
        if signers is not None:
            self.write(".github/acceptance-approvers", signers)
        self.g("add", "-A")
        self.g("commit", "-q", "-m", "base")
        self.base = self.rev("HEAD")
        self.g("checkout", "-q", "-b", "feat/x")

    def g(self, *args: str) -> str:
        return run(["git", "-c", "commit.gpgsign=false", *args], cwd=self.path)

    def rev(self, ref: str) -> str:
        return self.g("rev-parse", ref).strip()

    def write(self, rel: str, text: str) -> None:
        f = self.path / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")

    def append(self, rel: str, text: str) -> None:
        """Change a file after the test commit, in a commit of its own."""
        f = self.path / rel
        f.write_text(f.read_text(encoding="utf-8") + text, encoding="utf-8")
        self.g("add", rel)
        self.g("commit", "-q", "-m", f"edit {rel}")

    def fix(self) -> None:
        self.write("lib.py", "def answer():\n    return 2\n")
        self.write("src/lib.rs", LIB_RS % 2)
        self.g("commit", "-q", "-am", "fix")

    def test_commit(self, *paths: str) -> None:
        trailers = "".join(f"Acceptance-Test: {p}\n" for p in paths)
        self.g("commit", "-q", "-m", f"test: declare\n\n{trailers}Co-Authored-By: t <t@t>")

    def declare(self, *paths: str, body: str = TEST_BODY) -> None:
        for p in paths:
            self.write(p, body)
            self.g("add", p)
        self.test_commit(*paths)

    def declare_rs(self, rel: str, body: str = RS_BODY) -> None:
        self.write(rel, body)
        self.g("add", rel)
        self.test_commit(rel)

    def main_commit(self, rel: str, text: str) -> None:
        self.g("checkout", "-q", "main")
        self.write(rel, text)
        self.g("add", rel)
        self.g("commit", "-q", "-m", f"main: {rel}")
        self.base = self.rev("HEAD")
        self.g("checkout", "-q", "feat/x")

    def check(self, approvals: Path | None = None, env: dict | None = None) -> tuple[int, str]:
        args = ["bash", str(SCRIPT)]
        if approvals is not None:
            args += ["--approvals", str(approvals)]
        args += [self.base, self.rev("HEAD")]
        r = subprocess.run(args, cwd=self.path, env=env or ENV, check=False, capture_output=True, text=True)
        return r.returncode, r.stdout + r.stderr


def last(out: str) -> str:
    return out.strip().splitlines()[-1] if out.strip() else ""


def canon(out: str) -> list[str]:
    """The canonical failure lines of section 4.1, in order."""
    return [
        l
        for l in out.splitlines()
        if l.startswith("acceptance-check: approvable ") or l == "acceptance-check: not approvable"
    ]


def records(out: str) -> list[str]:
    p = "acceptance-check: approvable "
    return [l[len(p):] for l in canon(out) if l.startswith(p)]


def digest(recs: list[str]) -> str:
    return hashlib.sha256("".join(r + "\n" for r in recs).encode()).hexdigest()


def approval_text(recs, head, pr=PR, repo=REPO_NAME, failures=None, pending=42) -> str:
    return (
        "makiba-acceptance-approval v1\n"
        f"repo {repo}\n"
        f"pr {pr}\n"
        f"head {head}\n"
        f"failures {failures if failures is not None else digest(recs)}\n"
        f"pending {pending}\n" + "".join(r + "\n" for r in recs)
    )


def approvals_dir(folder: Path, key: Path, text: str) -> Path:
    """A folder holding one comment body: the text, a line ---, the signature of the text."""
    d = folder / "approvals"
    d.mkdir()
    msg = folder / "approval.txt"
    msg.write_text(text, encoding="utf-8")
    run(["ssh-keygen", "-q", "-Y", "sign", "-n", NAMESPACE, "-f", str(key), str(msg)])
    sig = (folder / "approval.txt.sig").read_text(encoding="utf-8")
    (d / "comment-1").write_text(text + "---\n" + sig, encoding="utf-8")
    return d



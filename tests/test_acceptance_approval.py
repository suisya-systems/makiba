"""Declared test of Issue 589 (acceptance approval, step 1 of docs/design/acceptance-approval.md):
scripts/acceptance-check.sh prints each failure once more in canonical form (section 4.1) and, given
--approvals <dir>, passes on the owner's signed approval of exactly that head and failure set
(section 4.3), for the allowed kinds of section 5 only.

Each case builds a scratch git repository, as tests/test_acceptance_check.py does, and runs the
repository's checker on it. Keys are made with ssh-keygen in the test's temporary folder; an
approval is the comment body of section 4.2: the approval text, a line `---`, the armored
signature."""


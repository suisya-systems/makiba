"""Issue #558: scripts/acceptance-check.sh builds and runs the declared tests outside the system's
temporary folders, so a declared test sees in the `acceptance` job the kind of path it sees in the
`tests` job. A declared Cargo test of a scratch repository records the CARGO_TARGET_TMPDIR it was
built with, at the test commit and at head; neither may lie under a temporary folder as
src/daemon/call.rs (agent_places) names them: /tmp, /private/tmp, /var/tmp and TMPDIR.

The scratch repository is made under the git folder of the tree holding this file (when the
checker runs this test from its own worktree, that is the checkout's .git), not under pytest's
tmp_path, because the checker's work folder follows the repository it checks. A temporary folder
that holds the scratch repository itself (a clone under /tmp) cannot be avoided by any checker and
is left out of the comparison; the TMPDIR passed to the checker never holds it, so it always counts.
"""

import os
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "acceptance-check.sh"

CARGO_TOML = '[package]\nname = "probe"\nversion = "0.0.0"\nedition = "2021"\n'
CARGO_LOCK = (
    "# This file is automatically @generated by Cargo.\n"
    "# It is not intended for manual editing.\n"
    "version = 4\n\n"
    '[[package]]\nname = "probe"\nversion = "0.0.0"\n'
)
LIB_RS = "pub fn answer() -> u32 {\n    %d\n}\n"
PROBE_RS = """use std::io::Write;

#[test]
fn records_its_target_tmpdir() {
    let out = std::env::var("PROBE_OUT").expect("PROBE_OUT is set");
    let mut f = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(out)
        .expect("open PROBE_OUT");
    writeln!(f, "{}", env!("CARGO_TARGET_TMPDIR")).expect("write PROBE_OUT");
    assert_eq!(probe::answer(), 2);
}
"""


def git_env() -> dict[str, str]:
    drop = ("CARGO_TARGET_DIR", "CARGO_BUILD_TARGET_DIR", "CARGO_BUILD_BUILD_DIR")
    return {
        **{k: v for k, v in os.environ.items() if k not in drop and not k.startswith("GIT_")},
        "GIT_AUTHOR_NAME": "t",
        "GIT_AUTHOR_EMAIL": "t@t",
        "GIT_COMMITTER_NAME": "t",
        "GIT_COMMITTER_EMAIL": "t@t",
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_CONFIG_NOSYSTEM": "1",
    }


def git(cwd: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-c", "commit.gpgsign=false", *args],
        cwd=cwd,
        env=git_env(),
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def write(root: Path, rel: str, text: str) -> None:
    f = root / rel
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(text, encoding="utf-8")


def under(path: Path, root: Path) -> bool:
    return path == root or root in path.parents


def common_dir(tree: Path) -> Path:
    out = git(tree, "rev-parse", "--path-format=absolute", "--git-common-dir").strip()
    return Path(out).resolve()


def test_declared_rust_test_sees_a_target_tmpdir_outside_the_temporary_folders(tmp_path):
    passed_tmpdir = tmp_path / "tmpdir"
    passed_tmpdir.mkdir()
    probe_out = tmp_path / "probe.txt"
    scratch = Path(tempfile.mkdtemp(prefix="acceptance-outside-tmp.", dir=common_dir(ROOT))).resolve()
    try:
        repo = scratch / "r"
        repo.mkdir()
        git(repo, "init", "-q", "-b", "main")
        write(repo, "Cargo.toml", CARGO_TOML)
        write(repo, "Cargo.lock", CARGO_LOCK)
        write(repo, "src/lib.rs", LIB_RS % 1)
        git(repo, "add", "-A")
        git(repo, "commit", "-q", "-m", "base")
        base = git(repo, "rev-parse", "HEAD").strip()
        git(repo, "checkout", "-q", "-b", "feat/x")
        write(repo, "tests/probe.rs", PROBE_RS)
        git(repo, "add", "tests/probe.rs")
        git(
            repo,
            "commit",
            "-q",
            "-m",
            "test: declare\n\nAcceptance-Test: tests/probe.rs\nCo-Authored-By: t <t@t>",
        )
        write(repo, "src/lib.rs", LIB_RS % 2)
        git(repo, "commit", "-q", "-am", "fix")
        head = git(repo, "rev-parse", "HEAD").strip()

        r = subprocess.run(
            ["bash", str(SCRIPT), base, head],
            cwd=repo,
            env={**git_env(), "PROBE_OUT": str(probe_out), "TMPDIR": str(passed_tmpdir)},
            check=False,
            capture_output=True,
            text=True,
        )
        out = r.stdout + r.stderr
        lines = out.strip().splitlines()

        # 1. the checker passes the scratch branch
        assert r.returncode == 0 and lines and lines[-1] == "ACCEPTANCE: pass", out

        # 2. the declared test ran twice: at the test commit, then at head
        recorded = probe_out.read_text(encoding="utf-8").splitlines() if probe_out.exists() else []
        assert len(recorded) == 2, (recorded, out)

        # 3. neither run's CARGO_TARGET_TMPDIR is under a temporary folder
        roots = [passed_tmpdir.resolve()]
        for t in ("/tmp", "/private/tmp", "/var/tmp", tempfile.gettempdir()):
            p = Path(t).resolve()
            if not under(scratch, p) and p not in roots:
                roots.append(p)
        for line in recorded:
            p = Path(line)
            assert p.is_absolute(), (line, out)
            resolved = p.resolve()
            for root in roots:
                assert not under(resolved, root), (
                    f"{line} is under the temporary folder {root}",
                    out,
                )

            # 4. it is the scratch repository's own build, a target folder's tmp
            assert under(resolved, scratch), (line, out)
            assert line.endswith("/target/tmp"), (line, out)

        # 5. the checker leaves no worktree, no work folder and no untracked file behind
        worktrees = [
            w for w in git(repo, "worktree", "list", "--porcelain").splitlines() if w.startswith("worktree ")
        ]
        assert len(worktrees) == 1, (worktrees, out)
        work_parent = common_dir(repo) / "acceptance-check"
        assert not work_parent.exists() or not any(work_parent.iterdir()), (
            sorted(str(p) for p in work_parent.iterdir()),
            out,
        )
        assert git(repo, "status", "--porcelain") == "", out
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
